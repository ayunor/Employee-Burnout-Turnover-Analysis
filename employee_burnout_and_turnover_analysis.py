def prepare_model_data(
    data: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Menyiapkan data untuk machine learning.

    Menghasilkan:
    - Data yang sudah diencoding
    - Data yang sudah distandardisasi
    """
    model_data = data.copy()

    categorical_columns = model_data.select_dtypes(
        include=["object", "category"]
    ).columns

    for column in categorical_columns:
        model_data[column] = (
            model_data[column]
            .astype("category")
            .cat.codes
        )

    model_data = model_data.drop(
        columns=[
            "EmployeeCount",
            "Over18",
            "StandardHours",
            "EmployeeNumber",
            "TenureGroup",
            "OverTime",
        ],
        errors="ignore",
    )

    model_data = model_data.apply(
        pd.to_numeric,
        errors="coerce",
    )

    model_data = model_data.fillna(
        model_data.median(numeric_only=True)
    )

    scaled_data = model_data.copy()

    feature_columns = [
        column
        for column in scaled_data.select_dtypes(
            include=["number"]
        ).columns
        if column not in [
            "Attrition",
            "BurnoutScore",
        ]
    ]

    scaler = StandardScaler()
    scaled_data[feature_columns] = scaler.fit_transform(
        scaled_data[feature_columns]
    )

    return model_data, scaled_data


