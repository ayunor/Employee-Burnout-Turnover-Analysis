def employee_clustering(
    original_data: pd.DataFrame,
    scaled_data: pd.DataFrame,
) -> pd.DataFrame:
    """
    Mengelompokkan karyawan menggunakan K-Means.

    Proses clustering menggunakan data terstandardisasi.
    Profil cluster dihitung menggunakan data asli.
    """
    cluster_features = [
        "BurnoutScore",
        "JobSatisfaction",
        "WorkLifeBalance",
        "YearsAtCompany",
        "NumCompaniesWorked",
        "OverTime_Encoded",
    ]

    missing_features = [
        column
        for column in cluster_features
        if column not in scaled_data.columns
    ]

    if missing_features:
        raise ValueError(
            "Fitur clustering tidak ditemukan: "
            f"{missing_features}"
        )

    cluster_input = scaled_data[cluster_features].copy()

    # ------------------------------------------------------------------------
    # Elbow Method
    # ------------------------------------------------------------------------
    inertia_values = []
    cluster_range = range(2, 10)

    for number_of_clusters in cluster_range:
        temporary_model = KMeans(
            n_clusters=number_of_clusters,
            random_state=RANDOM_STATE,
            n_init=10,
        )

        temporary_model.fit(cluster_input)
        inertia_values.append(temporary_model.inertia_)

    plt.figure(figsize=(9, 5))

    plt.plot(
        list(cluster_range),
        inertia_values,
        marker="o",
        color="#E74C3C",
        linewidth=2,
    )

    plt.axvline(
        x=3,
        color="#2C3E50",
        linestyle="--",
        linewidth=2,
        label="Jumlah cluster yang digunakan: 3",
    )

    plt.title(
        "Elbow Method untuk Menentukan Jumlah Cluster",
        fontweight="bold",
    )
    plt.xlabel("Jumlah Cluster")
    plt.ylabel("Inertia")
    plt.legend()
    plt.tight_layout()
    plt.show()

    # ------------------------------------------------------------------------
    # K-Means dengan 3 cluster
    # ------------------------------------------------------------------------
    clustering_model = KMeans(
        n_clusters=3,
        random_state=RANDOM_STATE,
        n_init=10,
    )

    cluster_labels = clustering_model.fit_predict(
        cluster_input
    )

    clustered_data = original_data.copy()
    clustered_data["Cluster"] = cluster_labels

    # ------------------------------------------------------------------------
    # PCA Visualization
    # ------------------------------------------------------------------------
    pca = PCA(
        n_components=2,
        random_state=RANDOM_STATE,
    )

    pca_result = pca.fit_transform(cluster_input)

    clustered_data["PCA1"] = pca_result[:, 0]
    clustered_data["PCA2"] = pca_result[:, 1]

