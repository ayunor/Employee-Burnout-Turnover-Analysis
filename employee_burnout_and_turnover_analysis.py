# 6. KLASIFIKASI ATTRITION
# ============================================================================

def attrition_classification(
    model_data: pd.DataFrame,
) -> None:
    """Memprediksi Attrition menggunakan Random Forest Classifier."""
    features = model_data.drop(
        columns=["Attrition"],
        errors="ignore",
    )

    target = model_data["Attrition"].astype(int)

    x_train, x_test, y_train, y_test = train_test_split(
        features,
        target,
        test_size=0.20,
        random_state=RANDOM_STATE,
        stratify=target,
    )

    model = RandomForestClassifier(
        n_estimators=200,
        max_depth=10,
        random_state=RANDOM_STATE,
        n_jobs=-1,
        class_weight="balanced",
    )

    model.fit(x_train, y_train)

    predictions = model.predict(x_test)
    probabilities = model.predict_proba(x_test)[:, 1]

    roc_auc = roc_auc_score(
        y_test,
        probabilities,
    )

    matrix = confusion_matrix(
        y_test,
        predictions,
        labels=[0, 1],
    )

    print_separator("KLASIFIKASI TURNOVER / ATTRITION")
    print(f"ROC-AUC Score : {roc_auc:.4f}")

    print("\nClassification Report:")
    print(
        classification_report(
            y_test,
            predictions,
            labels=[0, 1],
            target_names=["Tetap", "Resign"],
            zero_division=0,
        )
    )

    # ------------------------------------------------------------------------
    # Confusion Matrix dan ROC Curve
    # ------------------------------------------------------------------------
    figure, axes = plt.subplots(
        nrows=1,
        ncols=2,
        figsize=(14, 5),
    )

    sns.heatmap(
        matrix,
        annot=True,
        fmt="d",
        cmap="Blues",
        xticklabels=["Tetap", "Resign"],
        yticklabels=["Tetap", "Resign"],
        ax=axes[0],
    )

    axes[0].set_title(
        "Confusion Matrix",
        fontweight="bold",
    )
    axes[0].set_xlabel("Prediksi Model")
    axes[0].set_ylabel("Kondisi Aktual")

    false_positive_rate, true_positive_rate, _ = roc_curve(
        y_test,
        probabilities,
    )

    axes[1].plot(
        false_positive_rate,
        true_positive_rate,
        color="#E74C3C",
        linewidth=2,
        label=f"ROC-AUC = {roc_auc:.4f}",
    )

    axes[1].plot(
        [0, 1],
        [0, 1],
        color="#2C3E50",
        linestyle="--",
        linewidth=1,
    )

    axes[1].set_title(
        "ROC Curve",
        fontweight="bold",
    )
    axes[1].set_xlabel("False Positive Rate")
    axes[1].set_ylabel("True Positive Rate")
    axes[1].legend()

    plt.tight_layout()
    plt.show()


