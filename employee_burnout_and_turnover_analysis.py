def validate_required_columns(
    data: pd.DataFrame,
    required_columns: list[str],
) -> None:
    """Memastikan kolom penting tersedia di dataset."""
    missing_columns = [
        column for column in required_columns
        if column not in data.columns
    ]

    if missing_columns:
        raise ValueError(
            "Kolom berikut tidak ditemukan dalam dataset: "
            f"{missing_columns}"
        )


def convert_binary_columns(data: pd.DataFrame) -> pd.DataFrame:
    """
    Mengubah kolom biner penting menjadi format numerik.

    Attrition:
        No  -> 0
        Yes -> 1

    OverTime:
        No  -> 0
        Yes -> 1
    """
    result = data.copy()

    if result["Attrition"].dtype == "object":
        result["Attrition"] = (
            result["Attrition"]
            .astype(str)
            .str.strip()
            .str.lower()
            .map({
                "no": 0,
                "yes": 1,
            })
        )

    if result["OverTime"].dtype == "object":
        result["OverTime_Encoded"] = (
            result["OverTime"]
            .astype(str)
            .str.strip()
            .str.lower()
            .map({
                "no": 0,
                "yes": 1,
            })
        )
    else:
        result["OverTime_Encoded"] = pd.to_numeric(
            result["OverTime"],
            errors="coerce",
        )

    if result["Attrition"].isna().any():
        raise ValueError(
            "Kolom Attrition memiliki nilai selain No atau Yes."
        )

    if result["OverTime_Encoded"].isna().any():
        raise ValueError(
            "Kolom OverTime memiliki nilai yang tidak dikenali."
        )

    return result


def create_burnout_score(data: pd.DataFrame) -> pd.DataFrame:
    """
    Membuat Burnout Score simulasi pada rentang 0 sampai 1.

    Skor dibentuk berdasarkan:
    - Overtime
    - Work-life balance
    - Job satisfaction
    - Jumlah perusahaan sebelumnya
    - Masa kerja di perusahaan saat ini
    """
    result = data.copy()

    np.random.seed(RANDOM_STATE)

    overtime_component = (
        result["OverTime_Encoded"] * 0.35
    )

    work_life_component = (
        (4 - pd.to_numeric(result["WorkLifeBalance"], errors="coerce"))
        * 0.20
    )

    satisfaction_component = (
        (4 - pd.to_numeric(result["JobSatisfaction"], errors="coerce"))
        * 0.15
    )

    company_change_component = (
        pd.to_numeric(
            result["NumCompaniesWorked"],
            errors="coerce",
        )
        / 15
        * 0.10
    )

    short_tenure_component = (
        (
            pd.to_numeric(
                result["YearsAtCompany"],
                errors="coerce",
            )
            < 2
        ).astype(int)
        * 0.10
    )

    random_noise = np.random.normal(
        loc=0,
        scale=0.05,
        size=len(result),
    )

    result["BurnoutScore"] = (
        overtime_component
        + work_life_component
        + satisfaction_component
        + company_change_component
        + short_tenure_component
        + random_noise
    ).clip(0, 1)

    return result


