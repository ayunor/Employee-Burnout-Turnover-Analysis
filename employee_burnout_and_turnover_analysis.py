def correlation_analysis(data: pd.DataFrame) -> None:
    """
    Menampilkan heatmap korelasi yang telah diperbaiki.

    Kolom ID dan kolom konstan dikeluarkan karena tidak memiliki
    nilai analitis yang berguna.
    """
    excluded_columns = [
        "EmployeeNumber",
        "EmployeeCount",
        "StandardHours",
    ]

    correlation_data = data.copy()

    # Tambahkan variabel biner Overtime agar dapat dianalisis
    if "OverTime_Encoded" not in correlation_data.columns:
        correlation_data["OverTime_Encoded"] = (
            correlation_data["OverTime"]
            .astype(str)
            .str.strip()
            .str.lower()
            .map({
                "no": 0,
                "yes": 1,
            })
        )

    numeric_columns = correlation_data.select_dtypes(
        include=["number"]
    ).columns.tolist()

    numeric_columns = [
        column
        for column in numeric_columns
        if column not in excluded_columns
        and correlation_data[column].nunique(dropna=True) > 1
        and correlation_data[column].notna().sum() > 0
    ]

    correlation_matrix = correlation_data[numeric_columns].corr(
        method="pearson"
    )

    # ------------------------------------------------------------------------
    # Heatmap lengkap
    # ------------------------------------------------------------------------
    plt.figure(figsize=(18, 14))

    sns.heatmap(
        correlation_matrix,
        annot=True,
        fmt=".2f",
        cmap="RdBu_r",
        center=0,
        vmin=-1,
        vmax=1,
        linewidths=0.5,
        linecolor="white",
        square=True,
        cbar_kws={
            "label": "Koefisien Korelasi Pearson",
            "shrink": 0.8,
        },
    )

    plt.title(
        "HEATMAP KORELASI VARIABEL NUMERIK",
        fontsize=16,
        fontweight="bold",
        pad=20,
    )
    plt.xticks(
        rotation=45,
        ha="right",
    )
    plt.yticks(rotation=0)
    plt.tight_layout()
    plt.show()

    print_separator("MATRIKS KORELASI LENGKAP")
    print(correlation_matrix.round(3).to_string())

    # ------------------------------------------------------------------------
    # Daftar pasangan korelasi terkuat
    # ------------------------------------------------------------------------
    upper_triangle = correlation_matrix.where(
        np.triu(
            np.ones(correlation_matrix.shape),
            k=1,
        ).astype(bool)
    )

    correlation_pairs = (
        upper_triangle
        .stack()
        .reset_index()
    )

    correlation_pairs.columns = [
        "Variabel 1",
        "Variabel 2",
        "Korelasi",
    ]

    correlation_pairs["Korelasi Absolut"] = (
        correlation_pairs["Korelasi"].abs()
    )

    correlation_pairs = (
        correlation_pairs
        .sort_values(
            "Korelasi Absolut",
            ascending=False,
        )
        .drop(columns=["Korelasi Absolut"])
        .reset_index(drop=True)
    )

    print_separator("10 PASANGAN VARIABEL DENGAN KORELASI TERKUAT")
    print(
        correlation_pairs
        .head(10)
        .round(3)
        .to_string(index=False)
    )

    # ------------------------------------------------------------------------
    # Heatmap tanpa BurnoutScore untuk mengurangi risiko interpretasi bias
    # ------------------------------------------------------------------------
    correlation_without_burnout = correlation_matrix.drop(
        index=["BurnoutScore"],
        columns=["BurnoutScore"],
        errors="ignore",
    )

    plt.figure(figsize=(18, 14))

    sns.heatmap(
        correlation_without_burnout,
        annot=True,
        fmt=".2f",
        cmap="RdBu_r",
        center=0,
        vmin=-1,
        vmax=1,
        linewidths=0.5,
        linecolor="white",
        square=True,
        cbar_kws={
            "label": "Koefisien Korelasi Pearson",
            "shrink": 0.8,
        },
    )

    plt.title(
        "HEATMAP KORELASI TANPA BURNOUT SCORE",
        fontsize=16,
        fontweight="bold",
        pad=20,
    )
    plt.xticks(
        rotation=45,
        ha="right",
    )
    plt.yticks(rotation=0)
    plt.tight_layout()
    plt.show()


