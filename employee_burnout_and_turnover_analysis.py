def display_business_recommendations(
    data: pd.DataFrame,
) -> None:
    """Menampilkan rekomendasi berdasarkan hasil analisis."""
    highest_attrition_department = (
        data.groupby("Department")["Attrition"]
        .mean()
        .mul(100)
        .sort_values(ascending=False)
        .index[0]
    )

    highest_attrition_rate = (
        data.groupby("Department")["Attrition"]
        .mean()
        .mul(100)
        .max()
    )

    highest_burnout_cluster = (
        data.groupby("Cluster")["BurnoutScore"]
        .mean()
        .idxmax()
    )

    high_risk_count = (
        data["RiskLevel"] == "High"
    ).sum()

    overtime_high_burnout_count = (
        (
            data["OverTime_Encoded"] == 1
        )
        & (
            data["BurnoutScore"]
            > data["BurnoutScore"].mean()
        )
    ).sum()

    print_separator("REKOMENDASI BISNIS")

    print(
        f"1. Prioritaskan Cluster {highest_burnout_cluster} "
        "untuk intervensi burnout."
    )
    print(
        "   Rekomendasi: mentoring, evaluasi beban kerja, "
        "dan fleksibilitas jam kerja."
    )

    print(
        f"\n2. Terdapat {high_risk_count:,} karyawan "
        "dalam kategori High Risk."
    )
    print(
        "   Rekomendasi: lakukan check-in rutin dengan HR, "
        "evaluasi kompensasi, dan berikan dukungan tambahan."
    )

    print(
        f"\n3. Department dengan attrition rate tertinggi adalah "
        f"{highest_attrition_department} "
        f"({highest_attrition_rate:.2f}%)."
    )
    print(
        "   Rekomendasi: lakukan analisis lanjutan terkait "
        "beban kerja, kepemimpinan, dan kepuasan karyawan."
    )

    print(
        f"\n4. Terdapat {overtime_high_burnout_count:,} karyawan "
        "yang mengalami overtime dan memiliki Burnout Score "
        "di atas rata-rata."
    )
    print(
        "   Rekomendasi: evaluasi kebutuhan rekrutmen, "
        "otomatisasi proses, dan pembagian beban kerja."
    )


