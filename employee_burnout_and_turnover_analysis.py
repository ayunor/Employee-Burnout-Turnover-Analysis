# 8. EARLY WARNING SYSTEM
# ============================================================================

def early_warning_system(
    data: pd.DataFrame,
) -> pd.DataFrame:
    """
    Mengelompokkan karyawan berdasarkan tingkat risiko turnover.

    Penting:
    Fungsi ini menggunakan data asli, bukan data yang sudah
    distandardisasi, agar threshold memiliki makna yang benar.
    """
    result = data.copy()

    burnout_threshold = result["BurnoutScore"].quantile(0.75)
    satisfaction_threshold = result["JobSatisfaction"].quantile(0.25)
    tenure_threshold = 2

    result["RiskLevel"] = "Low"

    medium_risk = (
        (result["BurnoutScore"] > burnout_threshold)
        & (
            result["JobSatisfaction"]
            < satisfaction_threshold
        )
    )

    high_risk = (
        (result["BurnoutScore"] > burnout_threshold)
        & (
            result["JobSatisfaction"]
            < satisfaction_threshold
        )
        & (
            result["YearsAtCompany"]
            < tenure_threshold
        )
    )

    result.loc[medium_risk, "RiskLevel"] = "Medium"
    result.loc[high_risk, "RiskLevel"] = "High"

    risk_order = [
        "Low",
        "Medium",
        "High",
    ]

    risk_distribution = (
        result["RiskLevel"]
        .value_counts()
        .reindex(
            risk_order,
            fill_value=0,
        )
    )

    attrition_by_risk = (
        result
        .groupby("RiskLevel")["Attrition"]
        .mean()
        .mul(100)
        .reindex(risk_order)
    )

    print_separator(
        "EARLY WARNING SYSTEM - RISIKO TURNOVER"
    )

    print(
        f"Burnout Score threshold 75%       : "
        f"{burnout_threshold:.3f}"
    )
    print(
        f"Job Satisfaction threshold 25%    : "
        f"{satisfaction_threshold:.3f}"
    )
    print(
        f"Threshold masa kerja              : "
        f"{tenure_threshold} tahun"
    )

    print("\nDistribusi Level Risiko:")
    print(risk_distribution.to_string())

    print("\nAttrition Rate berdasarkan Level Risiko:")
    print(attrition_by_risk.round(2).to_string())

    # ------------------------------------------------------------------------
    # Visualisasi Early Warning System
    # ------------------------------------------------------------------------
    figure, axes = plt.subplots(
        nrows=1,
        ncols=2,
        figsize=(14, 5),
    )

    risk_colors = {
        "Low": "#2ECC71",
        "Medium": "#F39C12",
        "High": "#E74C3C",
    }

    colors = [
        risk_colors[level]
        for level in risk_order
    ]

    bars = axes[0].bar(
        risk_distribution.index,
        risk_distribution.values,
        color=colors,
    )

    axes[0].set_title(
        "Distribusi Level Risiko",
        fontweight="bold",
    )
    axes[0].set_xlabel("Level Risiko")
    axes[0].set_ylabel("Jumlah Karyawan")

    for bar, value in zip(
        bars,
        risk_distribution.values,
    ):
        axes[0].text(
            bar.get_x() + bar.get_width() / 2,
            bar.get_height(),
            str(value),
            ha="center",
            va="bottom",
            fontweight="bold",
        )

    bars = axes[1].bar(
        attrition_by_risk.index,
        attrition_by_risk.values,
        color=colors,
    )

    axes[1].axhline(
        result["Attrition"].mean() * 100,
        color="#2C3E50",
        linestyle="--",
        linewidth=2,
        label=(
            f"Rata-rata keseluruhan: "
            f"{result['Attrition'].mean() * 100:.1f}%"
        ),
    )

    axes[1].set_title(
        "Attrition Rate berdasarkan Level Risiko",
        fontweight="bold",
    )
    axes[1].set_xlabel("Level Risiko")
    axes[1].set_ylabel("Attrition Rate (%)")
    axes[1].legend()

    for bar, value in zip(
        bars,
        attrition_by_risk.values,
    ):
        if not np.isnan(value):
            axes[1].text(
                bar.get_x() + bar.get_width() / 2,
                bar.get_height(),
                f"{value:.1f}%",
                ha="center",
                va="bottom",
                fontweight="bold",
            )

    plt.tight_layout()
    plt.show()

    return result


