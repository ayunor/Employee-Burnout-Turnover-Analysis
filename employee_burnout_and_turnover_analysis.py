# ============================================================================

def burnout_regression(
    model_data: pd.DataFrame,
) -> None:
    """Memprediksi Burnout Score menggunakan Random Forest Regressor."""
    features = model_data.drop(
        columns=[
            "BurnoutScore",
            "Attrition",
        ],
        errors="ignore",
    )

    target = model_data["BurnoutScore"]

    x_train, x_test, y_train, y_test = train_test_split(
        features,
        target,
        test_size=0.20,
        random_state=RANDOM_STATE,
    )

    model = RandomForestRegressor(
        n_estimators=200,
        max_depth=10,
        random_state=RANDOM_STATE,
        n_jobs=-1,
    )

    model.fit(x_train, y_train)

    predictions = model.predict(x_test)

    r2 = r2_score(y_test, predictions)
    mse = mean_squared_error(y_test, predictions)
    rmse = np.sqrt(mse)

    print_separator("REGRESI BURNOUT SCORE")
    print(f"R² Score : {r2:.4f}")
    print(f"MSE      : {mse:.4f}")
    print(f"RMSE     : {rmse:.4f}")

    feature_importance = (
        pd.DataFrame(
            {
                "Feature": features.columns,
                "Importance": model.feature_importances_,
            }
        )
        .sort_values(
            "Importance",
            ascending=False,
        )
        .reset_index(drop=True)
    )

    print_separator("10 FITUR TERPENTING UNTUK PREDIKSI BURNOUT")
    print(
        feature_importance
        .head(10)
        .round(4)
        .to_string(index=False)
    )

    top_features = feature_importance.head(10)

    plt.figure(figsize=(10, 7))

    plt.barh(
        top_features["Feature"][::-1],
        top_features["Importance"][::-1],
        color="#E74C3C",
    )

    plt.title(
        "10 Fitur Terpenting untuk Prediksi Burnout",
        fontweight="bold",
    )
    plt.xlabel("Importance Score")
    plt.ylabel("Feature")
    plt.tight_layout()
    plt.show()


